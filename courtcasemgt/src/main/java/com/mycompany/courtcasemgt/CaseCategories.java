        private void loadCategories() {

            // SQL statement to retrieve all categories.
            String sql
                    = "SELECT category_id, category_name, description "
                    + "FROM case_categories "
                    + "ORDER BY category_id";

            try (
                    java.sql.Connection connection
                    = DBConnection.getConnection(); java.sql.PreparedStatement statement
                    = connection.prepareStatement(sql); java.sql.ResultSet result
                    = statement.executeQuery()) {

                // Get the table's existing model.
                javax.swing.table.DefaultTableModel model
                        = (javax.swing.table.DefaultTableModel) tblCategories.getModel();

                // Remove existing rows.
                model.setRowCount(0);

                // Go through every database record.
                while (result.next()) {

                    // Get category ID.
                    int id = result.getInt("category_id");

                    // Get category name.
                    String name
                            = result.getString("category_name");

                    // Get description.
                    String description
                            = result.getString("description");

                    // Add the record to the JTable.
                    model.addRow(new Object[]{
                        id,
                        name,
                        description
                    });
                }

            } catch (java.sql.SQLException e) {

                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Error loading categories: " + e.getMessage()
                );
            }
        }

