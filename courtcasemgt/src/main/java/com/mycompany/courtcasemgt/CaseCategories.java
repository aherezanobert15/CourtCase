    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        // Get the category name entered by the user.
        String categoryName = txtCategoryName.getText().trim();

        // Get the description entered by the user.
        String description = txtDescription.getText().trim();

        // Check whether the category name is empty.
        if (categoryName.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please enter the category name."
            );

            return;
        }

        // SQL statement for inserting a new category.
        String sql
                = "INSERT INTO case_categories "
                + "(category_name, description) "
                + "VALUES (?, ?)";

        // Connect to the database and execute the SQL.
        try (
                java.sql.Connection connection
                = DBConnection.getConnection(); java.sql.PreparedStatement statement
                = connection.prepareStatement(sql)) {

            // Put the category name into the first ?.
            statement.setString(1, categoryName);

            // Put the description into the second ?.
            statement.setString(2, description);

            // Execute the INSERT command.
            statement.executeUpdate();

            // Inform the user.
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Category saved successfully!"
            );

            // Clear the input fields.
            txtCategoryName.setText("");
            txtDescription.setText("");

            // Reload the table.
            loadCategories();

        } catch (java.sql.SQLException e) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Error saving category: " + e.getMessage()
            );
        }
    }//GEN-LAST:event_btnSaveActionPerformed

